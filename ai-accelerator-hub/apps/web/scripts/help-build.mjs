#!/usr/bin/env node
/**
 * Builds the in-app help from docs/help/SIMPLE_GUIDE.md (the one source of the Simple Guide):
 *   lib/help/guide.generated.ts — the guide split into numbered sections, read by the Help button and /help.
 * Run after editing the guide:  node scripts/help-build.mjs   (test/help.test.ts fails if this file is out of date).
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const md = readFileSync(join(here, '../../../docs/help/SIMPLE_GUIDE.md'), 'utf8').replace(/\r\n/g, '\n');
export function splitGuide(text) {
  const [head, ...parts] = text.split(/\n(?=## )/);
  const title = (head.match(/^# (.+)$/m) || [, 'Help'])[1].trim();
  const intro = head.replace(/^# .+\n+/, '').trim();
  const sections = parts.map(p => {
    const [first, ...rest] = p.split('\n');
    const m = /^## (\d+)\.\s+(.+)$/.exec(first.trim());
    if (!m) throw new Error(`Section heading must look like "## 7. Title": ${first}`);
    return { n: Number(m[1]), title: m[2].trim(), md: rest.join('\n').trim() };
  });
  return { title, intro, sections };
}
const guide = splitGuide(md);
const out = `/** GENERATED by scripts/help-build.mjs from docs/help/SIMPLE_GUIDE.md — edit the guide, then run the script. */\nexport const GUIDE = ${JSON.stringify(guide, null, 1)} as const;\n`;
writeFileSync(join(here, '../lib/help/guide.generated.ts'), out);
console.log(`help: ${guide.sections.length} sections`);
