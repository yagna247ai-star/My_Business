#!/usr/bin/env node
/**
 * Lists every interface text in the code: t('…') / t("…") calls and <Tr>…</Tr> elements.
 * Writes lib/i18n/keys.generated.ts. Run after adding text:  node scripts/i18n-extract.mjs
 * A test fails when the file is out of date, so a new text can never miss its translation.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'fs';
import { join, relative } from 'path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIRS = ['app', 'components', 'lib'];
const SKIP = /(_legacy|node_modules|\.next|keys\.generated|messages\.ts$)/;

export function extract(src) {
  const keys = new Set();
  const unq = s => s.replace(/\\(['"`\\])/g, '$1');
  for (const m of src.matchAll(/\btr?\(\s*'((?:[^'\\\n]|\\.)+)'/g)) keys.add(unq(m[1]));
  for (const m of src.matchAll(/\btr?\(\s*"((?:[^"\\\n]|\\.)+)"/g)) keys.add(unq(m[1]));
  // Fixed server and client messages the learner can see: errors from lib/server/errors helpers, and msg('…').
  for (const m of src.matchAll(/\b(?:msg|badRequest|conflict|forbidden|notFound|unauthorized|tooMany)\(\s*'((?:[^'\\\n]|\\.)+)'/g)) keys.add(unq(m[1]));
  for (const m of src.matchAll(/\bnotConfigured\(\s*'[^']*',\s*'((?:[^'\\\n]|\\.)+)'/g)) keys.add(unq(m[1]));
  for (const m of src.matchAll(/<Tr>([^<{}]+)<\/Tr>/g)) keys.add(m[1].replace(/\s+/g, ' ').trim().replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&'));
  return [...keys].filter(Boolean);
}

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (SKIP.test(p)) continue;
    if (statSync(p).isDirectory()) walk(p, out); else if (/\.(tsx?|mts)$/.test(f)) out.push(p);
  }
  return out;
}

export function allKeys() {
  const keys = new Set();
  for (const d of DIRS) for (const f of walk(join(ROOT, d))) for (const k of extract(readFileSync(f, 'utf8'))) keys.add(k);
  return [...keys].sort();
}

if (process.argv[1] && relative(process.argv[1], new URL(import.meta.url).pathname) === '') {
  const keys = allKeys();
  const body = `// Generated by scripts/i18n-extract.mjs — do not edit. Every interface text in the code (${keys.length}).\nexport const UI_KEYS: string[] = ${JSON.stringify(keys, null, 0).replace(/","/g, '",\n  "').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};\n`;
  writeFileSync(join(ROOT, 'lib/i18n/keys.generated.ts'), body);
  console.log(`i18n: ${keys.length} interface texts`);
}
